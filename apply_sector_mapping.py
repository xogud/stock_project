def map_sector(name: str, current_sector: str) -> tuple[str, str]:
    if name in EXACT:
        return EXACT[name], "manual"

    if current_sector and current_sector != "UNKNOWN":
        return SECTOR_NORMALIZE.get(current_sector, current_sector), "existing"

    for sector, keywords in KEYWORDS:
        if any(keyword in name for keyword in keywords):
            return sector, "keyword"

    return "기타", "fallback"


def main() -> None:
    if not PROCESSED_STOCK_INFO.exists():
        raise FileNotFoundError(PROCESSED_STOCK_INFO)

    stock_info = pd.read_csv(PROCESSED_STOCK_INFO, dtype={"code": str}, encoding="utf-8-sig")
    stock_info["code"] = stock_info["code"].astype(str).str.zfill(6)

    mapped_rows = []
    for row in stock_info.itertuples(index=False):
        sector, source = map_sector(str(row.name), str(row.sector))
        mapped_rows.append(
            {
                "stock_code": row.code,
                "ticker": row.ticker,
                "stock_name": row.name,
                "market": row.market,
                "old_sector": row.sector,
                "sector": sector,
                "mapping_source": source,
            }
        )

    mapping = pd.DataFrame(mapped_rows)
    stock_info["sector"] = mapping["sector"]
    MAPPING_FILE.parent.mkdir(parents=True, exist_ok=True)
    mapping.to_csv(MAPPING_FILE, index=False, encoding="utf-8-sig")
    stock_info.to_csv(PROCESSED_STOCK_INFO, index=False, encoding="utf-8-sig")

    mysql_ready = stock_info.rename(columns={"code": "stock_code", "name": "stock_name"})[
        ["stock_code", "ticker", "stock_name", "market", "sector"]
    ]
    MYSQL_STOCK_INFO.parent.mkdir(parents=True, exist_ok=True)
    mysql_ready.to_csv(MYSQL_STOCK_INFO, index=False, encoding="cp949")

    sector_by_code = dict(zip(mapping["stock_code"].astype(str).str.zfill(6), mapping["sector"]))
    feature_updates = []
    for feature_path, encoding in [
        (PROCESSED_FEATURE_DATA, "utf-8-sig"),
        (MYSQL_FEATURE_DATA, "cp949"),
    ]:
        if not feature_path.exists():
            continue
        feature_data = pd.read_csv(feature_path, dtype={"stock_code": str}, encoding=encoding)
        if "stock_code" not in feature_data.columns or "sector" not in feature_data.columns:
            continue
        normalized_code = feature_data["stock_code"].astype(str).str.zfill(6)
        mapped_sector = normalized_code.map(sector_by_code)
        feature_data["sector"] = mapped_sector.fillna(feature_data["sector"]).fillna("기타")
        feature_data.to_csv(feature_path, index=False, encoding=encoding)
        feature_updates.append(f"{feature_path} rows={len(feature_data)}")

    print(f"rows={len(stock_info)}")
    print(f"mapping_file={MAPPING_FILE.resolve()}")
    print("sector_counts")
    print(stock_info["sector"].value_counts().to_string())
    print("mapping_sources")
    print(mapping["mapping_source"].value_counts().to_string())
    if feature_updates:
        print("feature_updates")
        print("\n".join(feature_updates))


if __name__ == "__main__":
    main()
